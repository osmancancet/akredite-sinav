import { chromium } from "playwright-core";
const BASE = process.argv[2] ?? "http://127.0.0.1:4173/app";
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser", headless: true });
const ctx = await b.newContext({ viewport: { width: 1400, height: 900 } });
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto(BASE);
await page.getByText("Demo veriyle keşfet").click();
await page.getByText("dönem iş akışı").first().waitFor();
await page.evaluate(async () => { await navigator.serviceWorker.ready; });
await page.waitForTimeout(4000);
const cached = await page.evaluate(async () => (await (await caches.open("akredite-sinav-v3")).keys()).filter((r) => r.url.includes("/frameworks/")).length);
console.log("framework files cached:", cached);
await ctx.setOffline(true);
await page.reload();
await page.getByText("dönem iş akışı").first().waitFor({ timeout: 15000 });
await page.evaluate(() => (location.hash = "/akreditasyon"));
await page.getByRole("button", { name: "Akreditasyon ekle", exact: true }).click();
await page.getByText(/Ölçüt kataloğu · 32 çerçeve/).waitFor({ timeout: 10000 });
const card = page.locator("div.rounded-xl").filter({ hasText: /^MÜDEK/ }).first();
await card.getByRole("button", { name: "Bu akreditasyonla çalış" }).click();
await page.getByRole("button", { name: "Çalışma alanını oluştur" }).click();
await page.getByText(/MÜDEK çalışma alanı açıldı/).waitFor({ timeout: 10000 });
console.log("OFFLINE catalog + activate MÜDEK: PASS");
console.log("errors:", errors.length ? errors.join(" | ") : "none");
await b.close();
